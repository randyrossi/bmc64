"""Interactively save a local rig configuration and create ./run_tests."""

import argparse
import ipaddress
import json
import math
import os
import sys
import tempfile
from pathlib import Path
from typing import Callable
from urllib.parse import urlsplit

from run_smoke import HERE, load_setup, parser


LAUNCHER = """#!/bin/sh
# Generated by configure_test_setup.py; settings are in test_setup.json.
set -eu
TEST_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
exec python3 "$TEST_DIR/run_smoke.py" --config "$TEST_DIR/test_setup.json" --execute "$@"
"""


def ask_text(label: str, default: str = "", *, required: bool = False,
             validate: Callable[[str], object] | None = None) -> str:
    while True:
        suffix = f" [{default}]" if default else ""
        answer = input(f"{label}{suffix}: ").strip()
        value = answer or default
        if not required and value == "-":
            value = ""
        if required and not value:
            print("A value is required.")
            continue
        try:
            if any(char in value for char in "\r\n\0"):
                raise ValueError("Use a single-line value.")
            if validate:
                validate(value)
        except ValueError as error:
            print(f"Invalid value: {error}")
            continue
        return value


def ask_yes_no(label: str, default: bool) -> bool:
    while True:
        answer = input(f"{label} [{'Y/n' if default else 'y/N'}]: ").strip().lower()
        if not answer:
            return default
        if answer in ("y", "yes"):
            return True
        if answer in ("n", "no"):
            return False
        print("Enter yes or no.")


def device_path(value: str) -> None:
    if value and not Path(value).is_absolute():
        raise ValueError("Use an absolute path, preferably /dev/serial/by-id/... for UARTs.")


def discover_devices(kind: str, root: Path = Path("/dev")) -> list[str]:
    patterns = (
        ("serial/by-id/*", "serial/by-path/*", "ttyUSB*", "ttyACM*", "ttyAMA*", "ttyS*")
        if kind == "uart" else
        ("v4l/by-id/*", "v4l/by-path/*", "video*")
    )
    devices = []
    seen = set()
    for pattern in patterns:
        for path in sorted(root.glob(pattern)):
            if not path.exists():
                continue
            resolved = path.resolve()
            if resolved not in seen:
                seen.add(resolved)
                devices.append(str(path))
    return devices


def ask_device(label: str, devices: list[str], default: str = "", *,
               required: bool = False, exclude: str = "") -> str:
    choices = [
        path for path in devices
        if not exclude or os.path.realpath(path) != os.path.realpath(exclude)
    ]
    print(f"\n{label}:")
    for number, path in enumerate(choices, 1):
        target = os.path.realpath(path)
        suffix = f" -> {target}" if target != path else ""
        print(f"  {number}) {path}{suffix}")
    if not choices:
        print("  No devices discovered; enter an absolute path manually.")
    else:
        print("Choose a number or type an absolute path.")
    if not required:
        print("Enter '-' for none.")

    def selected(value: str) -> str:
        if value.isdecimal():
            number = int(value)
            if not 1 <= number <= len(choices):
                raise ValueError(f"Choose a number between 1 and {len(choices)}.")
            return choices[number - 1]
        return value

    def validate(value: str) -> None:
        path = selected(value)
        device_path(path)
        if path and exclude and os.path.realpath(path) == os.path.realpath(exclude):
            raise ValueError("This adapter is already selected for the Pico.")

    return selected(ask_text(label, default, required=required, validate=validate))


def positive_timeout(value: str) -> None:
    number = float(value)
    if not math.isfinite(number) or number <= 0:
        raise ValueError("Timeout must be finite and positive.")


def write_atomic(path: Path, text: str, mode: int) -> None:
    with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=path.parent, delete=False) as temporary:
        name = Path(temporary.name)
        try:
            temporary.write(text)
            temporary.flush()
            os.fchmod(temporary.fileno(), mode)
            os.replace(name, path)
        finally:
            if name.exists():
                name.unlink()


def configure(directory: Path = HERE) -> bool:
    config_path = directory / "test_setup.json"
    launcher_path = directory / "run_tests"
    if launcher_path.exists() and launcher_path.read_text(encoding="utf-8") != LAUNCHER:
        raise RuntimeError(f"{launcher_path} already exists and is not the generated launcher")
    saved = load_setup(config_path) if config_path.exists() else {}
    defaults = vars(parser().parse_args([]))
    defaults.update(saved)
    print("Configure the C64 hardware smoke test. Devices are listed but never opened.")
    print("Enter keeps the displayed value; '-' clears an optional value.")
    print("Use stable UART paths from /dev/serial/by-id/ where available.")
    saved_url = urlsplit(defaults["url"] or "")
    address = ask_text("BMC64 IP address", saved_url.hostname or "",
                       required=True, validate=ipaddress.ip_address)
    host = f"[{address}]" if ipaddress.ip_address(address).version == 6 else address
    port = f":{saved_url.port}" if saved_url.port is not None else ""
    url = f"{saved_url.scheme or 'http'}://{host}{port}/"
    uart_devices = discover_devices("uart")
    pico_uart = ask_device("Pico UART device", uart_devices, defaults["pico_uart"] or "",
                          required=True)
    bmc_uart = ask_device("BMC64 diagnostic UART (optional)", uart_devices,
                         defaults["bmc_uart"] or "", exclude=pico_uart)
    settings = {
        "url": url,
        "pico_uart": pico_uart,
        "bmc_uart": bmc_uart,
        "video": ask_device("HDMI video device", discover_devices("video"),
                            defaults["video"], required=True),
        "audio": ask_text("HDMI ALSA audio device", defaults["audio"], required=True),
        "setup": ask_text("Board/profile/ROM/setup notes (optional)", defaults["setup"]),
        "timeout": float(ask_text("Guest assertion timeout in seconds", str(defaults["timeout"]),
                                  required=True, validate=positive_timeout)),
        "ask_pin": ask_yes_no("Does the Web UI require a PIN?", defaults["ask_pin"]),
    }
    if bmc_uart and os.path.realpath(bmc_uart) == os.path.realpath(pico_uart):
        raise ValueError("Pico and BMC64 UART paths must be different; no settings saved")
    print("\nThe generated run_tests command WILL upload/autostart the diagnostic,")
    print("reset the emulated C64, record HDMI/audio and send Space through the Pico.")
    print("Close viewers/serial terminals and save guest work before running it.")
    if not ask_yes_no("Save this setup and create run_tests?", True):
        print("Cancelled; existing setup unchanged.")
        return False
    config_path.parent.mkdir(parents=True, exist_ok=True)
    write_atomic(launcher_path, LAUNCHER, 0o755)
    write_atomic(config_path, json.dumps(settings, indent=2) + "\n", 0o600)
    print(f"\nSaved setup: {config_path}")
    print(f"Reusable launcher: {launcher_path}")
    print("Run ./run_tests from this folder, or use its full path from anywhere.")
    print("Re-run configure_test_setup.py only when the setup changes.")
    if settings["ask_pin"]:
        print("The PIN is not saved; each test run will prompt for it.")
    return True


def main() -> int:
    argparse.ArgumentParser(description=__doc__).parse_args()
    try:
        return 0 if configure() else 1
    except (EOFError, KeyboardInterrupt):
        print("\nConfiguration cancelled.", file=sys.stderr)
        return 1
    except (OSError, ValueError, RuntimeError) as error:
        print(f"Configuration failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
