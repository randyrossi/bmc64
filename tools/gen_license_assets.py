#!/usr/bin/env python3
"""Generate SD-card license copies and OSD text from repository license files."""

import argparse
import json
from pathlib import Path
import re
import sys
import textwrap


REPO_ROOT = Path(__file__).resolve().parent.parent
LICENSE_COPIES = {
    "GPL-3.0.txt": "LICENSE",
    "GPL-2.0.txt": "third_party/vice-3.3/COPYING",
    "LGPL-2.1.txt": "third_party/circle-stdlib/libs/circle-newlib/COPYING.LIB",
    "VICE.txt": "third_party/vice-3.3/README",
    "Plus4Emu.txt": "third_party/plus4emu/README",
    "dotconf.txt": "third_party/plus4emu/licenses/LICENSE.dotconf",
    "libsndfile-interface.txt": "third_party/plus4emu/licenses/LICENSE.libsndfile",
    "zlib.txt": "third_party/zlib/LICENSE",
    "Bescii-CC0.txt": "tools/font_gen/LICENSE-Bescii.txt",
    "newlib.txt": "third_party/circle-stdlib/libs/circle-newlib/COPYING.NEWLIB",
    "libgloss.txt": "third_party/circle-stdlib/libs/circle-newlib/COPYING.LIBGLOSS",
}


def osd_lines(text: str, width: int) -> list[str]:
    if width < 1:
        raise ValueError("OSD line width must be positive")
    if not text.strip():
        raise ValueError("The main license is empty")
    if any(ord(char) > 126 or (ord(char) < 32 and char not in "\n\r\t")
           for char in text):
        raise ValueError("The main license must contain printable ASCII text")
    lines = []
    for source_line in text.splitlines():
        lines.extend(textwrap.wrap(
            source_line.expandtabs().strip(), width=width,
            break_long_words=True, break_on_hyphens=False,
        ) or [""])
    return lines


def generated_assets(root: Path) -> dict[Path, bytes]:
    header = (root / "third_party/common/text.h").read_text(encoding="ascii")
    ui_header = (root / "third_party/common/ui.h").read_text(encoding="utf-8")
    width_match = re.search(r"^#define LICENSE_LINE_WIDTH (\d+)$", header, re.M)
    menu_match = re.search(r"^#define MAX_MENU_STR\s+(\d+)$", ui_header, re.M)
    if width_match is None or menu_match is None:
        raise ValueError("Cannot determine license/menu text limits")
    width = int(width_match[1])
    if width >= int(menu_match[1]):
        raise ValueError("License lines would be truncated by the OSD menu")

    assets = {}
    for name, source in LICENSE_COPIES.items():
        data = (root / source).read_bytes()
        if not data.strip():
            raise ValueError(f"Empty license source: {source}")
        assets[root / "sdcard/licenses" / name] = data

    lines = osd_lines(assets[root / "sdcard/licenses/GPL-3.0.txt"].decode("ascii"),
                      width)
    content = "/* Generated by tools/gen_license_assets.py from LICENSE. */\n"
    content += "".join(f"    {json.dumps(line)},\n" for line in lines)
    assets[root / "third_party/common/license_text.inc"] = content.encode("ascii")
    return assets


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if generated files are missing or stale")
    args = parser.parse_args()
    try:
        assets = generated_assets(REPO_ROOT)
        # These are maintained notices, not generated from a component source.
        for name in ("README.txt", "Apache-2.0.txt", "crt-pi.txt",
                     "GCC-Runtime.txt", "RaspberryPi-Firmware.txt"):
            if not (REPO_ROOT / "sdcard/licenses" / name).read_bytes().strip():
                raise ValueError(f"Empty license notice: {name}")
        stale = False
        for destination, data in assets.items():
            if destination.exists() and destination.read_bytes() == data:
                continue
            if args.check:
                print(f"Stale or missing: {destination.relative_to(REPO_ROOT)}",
                      file=sys.stderr)
                stale = True
            else:
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_bytes(data)
        if stale:
            return 1
    except (OSError, UnicodeError, ValueError) as error:
        print(f"License asset generation failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
